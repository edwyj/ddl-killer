import assert from 'node:assert/strict';
import test from 'node:test';
process.env.DB_PATH=':memory:';
process.env.AI_INVITE_SECRET='invite-test-secret-at-least-32-characters';
process.env.AI_HOSTED_ENABLED='true';
process.env.AI_HOSTED_DAILY_LIMIT='3';
const {db}=await import('../src/db.js');
db.prepare('INSERT INTO users(id,username,password_hash) VALUES(1,?,?)').run('invite_one','test');
db.prepare('INSERT INTO users(id,username,password_hash) VALUES(2,?,?)').run('invite_two','test');
const m=await import('../src/ai-invites.js');
const q=await import('../src/ai-quota.js');
const now=Date.parse('2026-09-30T02:00:00Z');
test.beforeEach(()=>{db.exec('DELETE FROM ai_invites; DELETE FROM ai_invite_batches; DELETE FROM ai_invite_audit; DELETE FROM ai_quota_daily; DELETE FROM ai_quota_reservations;'); delete process.env.AI_HOSTED_GLOBAL_DAILY_LIMIT;});
test('issue is idempotent, plaintext not persisted, batch conflicts and rolling cap rejected',()=>{
  const a=m.issueInvites('week',2,'request-key-one',now);
  assert.deepEqual(m.issueInvites('week',2,'request-key-one',now),a);
  assert.equal(db.prepare('SELECT count(*) n FROM ai_invites').get().n,2);
  assert.ok(!JSON.stringify(db.prepare('SELECT * FROM ai_invites').all()).includes(a.invites[0].code));
  assert.throws(()=>m.issueInvites('month',2,'request-key-one',now),{code:'INVITE_CONFLICT'});
  m.issueInvites('week',10,'request-key-two',now); m.issueInvites('week',10,'request-key-three',now);
  assert.throws(()=>m.issueInvites('week',10,'request-key-four',now),{code:'INVITE_ISSUE_LIMIT'});
  assert.throws(()=>m.issueInvites('invalid',1,'request-key-five',now));
});
test('redeem binds once, retries preserve expiry; stolen, expired and revoked codes fail',()=>{
  const {code,id}=m.issueInvites('week',1,'request-key-one',now).invites[0];
  assert.equal(m.previewInvite(code,1,now).dailyLimit,10);
  m.redeemInvite(code,1,now);
  const end=m.activeInvites(1,now)[0].expiresAt;
  m.redeemInvite(code,1,now+1000);
  assert.equal(m.activeInvites(1,now)[0].expiresAt,end);
  assert.throws(()=>m.redeemInvite(code,2,now),{code:'INVITE_INVALID'});
  assert.equal(m.effectiveInviteLimit(1,3,now+7*86400000),3);
  m.revokeInvite(id,now+2000);
  assert.throws(()=>m.redeemInvite(code,1,now+3000),{code:'INVITE_INVALID'});
  const other=m.issueInvites('month',1,'request-key-two',now).invites[0].code;
  assert.throws(()=>m.redeemInvite(other,1,now+7*86400000),{code:'INVITE_INVALID'});
});
test('same-day usage retained, no additive stacking, global cap and BYOK preserved',async()=>{
  const r=await q.reserveHostedGeneration(1,new Date(now));q.consumeReservation(r.id);
  m.redeemInvite(m.issueInvites('week',1,'request-key-one',now).invites[0].code,1,now);
  assert.equal(q.quotaStatus(1,new Date(now)).remaining,9);
  m.redeemInvite(m.issueInvites('month',1,'request-key-two',now).invites[0].code,1,now);
  assert.equal(q.quotaStatus(1,new Date(now)).limit,10);
  const results=await Promise.allSettled(Array.from({length:12},()=>q.reserveHostedGeneration(1,new Date(now))));
  assert.equal(results.filter(r=>r.status==='fulfilled').length,9);
  process.env.AI_HOSTED_GLOBAL_DAILY_LIMIT='10';
  await assert.rejects(q.reserveHostedGeneration(2,new Date(now)),{code:'AI_GLOBAL_QUOTA_EXHAUSTED'});
  assert.equal(await q.reserveGeneration('byok',2,new Date(now)),null);
  assert.equal(q.quotaStatus(1,new Date(now+86400000)).remaining,10);
});
